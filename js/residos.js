function selecionarAtalho(tipo) {
  document.getElementById("residuoInput").value = tipo;
  classificarResiduo();
}

function classificarResiduo() {
  const campo = document.getElementById("residuoInput");
  const textoOriginal = campo.value.trim();

  const entrada = textoOriginal
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");

  if (entrada === "") return;

  const box = document.getElementById("resultado");
  const indicador = document.getElementById("corIndicador");
  const titulo = document.getElementById("tituloLixeira");
  const texto = document.getElementById("orientacaoTexto");

  box.classList.remove("oculto");

  const encontrada = CATEGORIAS.find((cat) =>
    cat.palavras.some((palavra) => entrada.includes(palavra))
  );

  let categoria = "";

  if (encontrada) {
    indicador.style.background = encontrada.cor;
    categoria = encontrada.nome;
    texto.textContent = encontrada.orientacao;
  } else {
    indicador.style.background = "#64748b";
    categoria = "Resíduo não identificado";
    texto.textContent =
      "Não encontrei esse item na base local. Tente informar o material principal (ex.: papel, plastico, vidro, metal, organico, eletronico ou rejeito).";
  }

  titulo.textContent = categoria;
  registrarHistorico(textoOriginal, categoria);
}

function registrarHistorico(item, destino) {
  totalConsultas++;
  document.getElementById("contador").textContent = totalConsultas;
  document.getElementById("historicoBox").classList.remove("oculto");

  const lista = document.getElementById("listaHistorico");
  const li = document.createElement("li");
  li.innerHTML = `<strong>${item}</strong> → ${destino}`;
  lista.prepend(li);
}